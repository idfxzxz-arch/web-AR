export const calculateDimensionScores = (answers) => {
  const dimensionResults = dimensionsData.map((dim) => {
    const dimQuestionIds = dim.questions.map((q) => q.id);
    const sum = dimQuestionIds.reduce((acc, qId) => {
      const val = parseInt(answers[qId], 10) || 0;
      return acc + val;
    }, 0);

    // Sd = (Total Skor Riil Dimensi d / 15) * 100%
    const percentage = Math.round((sum / 15) * 100);

    let category = "Perlu Peningkatan";
    let categoryBadge = "bg-red-100 text-red-800 border-red-200";
    let recommendation = dim.recommendations.low;

    if (percentage >= 80) {
      category = "Sangat Tinggi";
      categoryBadge = "bg-emerald-100 text-emerald-800 border-emerald-200";
      recommendation = dim.recommendations.high;
    } else if (percentage >= 60) {
      category = "Tinggi";
      categoryBadge = "bg-blue-100 text-blue-800 border-blue-200";
      recommendation = dim.recommendations.high;
    } else if (percentage >= 40) {
      category = "Cukup";
      categoryBadge = "bg-amber-100 text-amber-800 border-amber-200";
      recommendation = dim.recommendations.medium;
    }

    return {
      id: dim.id,
      name: dim.name,
      shortName: dim.shortName,
      rawScore: sum,
      maxScore: 15,
      percentage,
      category,
      categoryBadge,
      recommendation,
      color: dim.color
    };
  });

  const totalRaw = dimensionResults.reduce((acc, r) => acc + r.rawScore, 0);
  const overallPercentage = Math.round((totalRaw / 75) * 100);

  return {
    dimensionResults,
    totalRaw,
    maxPossible: 75,
    overallPercentage
  };
};

